import AppKit

@MainActor
func verifyPositionVisible(_ scroll: ReaderScrollView, _ position: Int, _ message: String) throws {
    let visible = scroll.readerTextView.accessibilityVisibleCharacterRange()
    try verify(NSLocationInRange(position, visible),
               "\(message): target \(position), visible \(visible)")
}

@MainActor
func testReader() throws {
    _ = NSApplication.shared
    let window = ReaderNativeWindow(contentRect: NSRect(x: 50, y: 50, width: 860, height: 720),
                          styleMask: [.titled, .resizable, .closable], backing: .buffered, defer: false)
    let scroll = ReaderScrollView()
    configureReaderWindow(window)
    try verify(window.styleMask.contains(.resizable), "Window remains resizable")
    try verify(window.styleMask.contains(.fullSizeContentView), "Full size content")
    try verify(window.titleVisibility == .hidden, "Hidden title")
    try verify(window.standardWindowButton(.closeButton)?.isHidden == true, "Hidden window buttons")
    window.contentView = scroll
    scroll.load(String(repeating: "窗外的风吹过山林，远处传来清脆的鸟鸣。\n", count: 10_000))
    window.orderFront(nil)
    window.contentView?.layoutSubtreeIfNeeded()
    RunLoop.main.run(until: Date(timeIntervalSinceNow: 0.1))
    try verify(scroll.readerTextView.textLayoutManager != nil, "TextKit 2 must remain active")
    try verify(scroll.readerTextView.frame.height > scroll.bounds.height, "Document must scroll")
    scroll.contentView.scroll(to: NSPoint(x: 0, y: 3000))
    scroll.reflectScrolledClipView(scroll.contentView)
    RunLoop.main.run(until: Date(timeIntervalSinceNow: 0.1))
    try verify(scroll.contentView.bounds.minY > 0, "Scroll origin changes")
    let beforeFont = scroll.topCharacterIndex()
    try verify(beforeFont > 0, "Visible top character captured")
    scroll.applyFont(26)
    RunLoop.main.run(until: Date(timeIntervalSinceNow: 0.1))
    try verify(scroll.readerTextView.font?.pointSize == 26, "Font update")
    try verifyPositionVisible(scroll, beforeFont, "Font change preserves text anchor")
    scroll.applyTheme(.dark)
    try verify(scroll.readerTextView.backgroundColor == ReaderTheme.dark.background, "Dark background")
    scroll.applyTheme(.light)
    try verify(scroll.readerTextView.textColor == ReaderTheme.light.foreground, "Light foreground")
    window.setContentSize(NSSize(width: 1100, height: 600))
    window.contentView?.layoutSubtreeIfNeeded()
    try verify(scroll.readerTextView.textContainerInset.width >= 32, "Reading margins")
    scroll.restorePosition(70_000)
    RunLoop.main.run(until: Date(timeIntervalSinceNow: 0.1))
    try verifyPositionVisible(scroll, 70_000, "Restore distant character index")
    let beforeResize = scroll.topCharacterIndex()
    window.setContentSize(NSSize(width: 550, height: 650))
    window.contentView?.layoutSubtreeIfNeeded()
    RunLoop.main.run(until: Date(timeIntervalSinceNow: 0.1))
    try verifyPositionVisible(scroll, beforeResize, "Resize preserves text anchor")
    window.orderOut(nil)
    print("PASS: TextKit 2, native scrolling, resizing, margins, hidden title/window buttons")

    guard let defaults = UserDefaults(suiteName: "NovelReaderTests.\(UUID())") else {
        throw NSError(domain: "Test defaults unavailable", code: 1)
    }
    let state = ReadingState(defaults: defaults)
    try verify(state.fontSize == 20, "Default font")
    state.adjustFont(by: 100)
    try verify(state.fontSize == 40, "Upper font boundary")
    state.adjustFont(by: -100)
    try verify(state.fontSize == 12, "Lower font boundary")
    state.adjustFont(by: 2)
    try verify(ReadingState(defaults: defaults).fontSize == 14, "Persisted font")
    state.toggleTheme()
    try verify(ReadingState(defaults: defaults).theme == .dark, "Persisted theme")
    state.toggleTheme()
    try verify(ReadingState(defaults: defaults).theme == .light, "Return to light theme")
    state.setForegroundColor(NSColor(srgbRed: 0.2, green: 0.4, blue: 0.6, alpha: 1))
    state.setBackgroundColor(NSColor(srgbRed: 0.8, green: 0.7, blue: 0.5, alpha: 1))
    state.hidesWindowBorder = true
    let appearance = ReadingState(defaults: defaults)
    try verify(appearance.customForeground == state.customForeground, "Custom foreground persists")
    try verify(appearance.customBackground == state.customBackground, "Custom background persists")
    try verify(appearance.hidesWindowBorder, "Border preference persists")
    scroll.applyColors(foreground: appearance.foregroundColor, background: appearance.backgroundColor)
    try verify(scroll.readerTextView.textColor == appearance.foregroundColor, "Custom text color applied")
    try verify(scroll.backgroundColor == appearance.backgroundColor, "Custom scroll background applied")
    try verify(scroll.readerTextView.backgroundColor == appearance.backgroundColor, "Custom text background applied")
    state.toggleTheme()
    let preset = ReadingState(defaults: defaults)
    try verify(preset.customForeground == nil && preset.customBackground == nil, "Theme restores preset colors")
    try verify(preset.hidesWindowBorder, "Theme preserves border preference")
    configureReaderWindow(window, hidesBorder: true)
    try verify(!window.styleMask.contains(.titled) && !window.hasShadow, "Border and shadow hidden")
    try verify(window.styleMask.contains(.resizable) && window.canBecomeKey, "Borderless window resizes and accepts focus")
    configureReaderWindow(window, hidesBorder: false)
    try verify(window.styleMask.contains(.titled) && window.hasShadow, "Border can be restored")
    print("PASS: font updates, boundaries, persistence")
    let store = ReadingProgressStore(defaults: defaults)
    let url = URL(fileURLWithPath: "/local/first.txt")
    let other = URL(fileURLWithPath: "/local/second.txt")
    store.savePosition(12_345, for: url)
    store.savePosition(77, for: other)
    let reopened = ReadingProgressStore(defaults: defaults)
    try verify(reopened.position(for: url) == 12_345, "Position persistence")
    try verify(reopened.position(for: other) == 77, "Separate file positions")
    reopened.savePosition(-10, for: other)
    try verify(reopened.position(for: other) == 0, "Negative position clamped")
    print("PASS: character anchors, font/resize preservation, per-file progress persistence")
}
